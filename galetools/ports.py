"""Ports: the interfaces the application layer needs from the outside world.

Adapters in `galetools.adapters` implement them; tests use in-memory fakes.
"""
from __future__ import annotations

from pathlib import Path
from typing import Protocol

from .domain.models import InstalledMod, PackageInfo, PackageRef


class ProfileRepository(Protocol):
    """Gale profiles on disk (read-mostly)."""

    def list_profiles(self) -> list[str]: ...
    def installed_mods(self, profile: str) -> list[InstalledMod]: ...
    def read_log(self, profile: str) -> str | None: ...
    def file_exists(self, mod: InstalledMod, relative: str) -> bool: ...
    def write_mod_file(self, mod: InstalledMod, kind: str, relative: str, data: bytes) -> bool: ...
    def build_test_profile(self, profile: str, mods: list[InstalledMod], name: str) -> Path: ...
    def read_text(self, path: Path) -> str | None: ...


class PackageRegistry(Protocol):
    """Thunderstore."""

    def info(self, ref: PackageRef) -> PackageInfo: ...
    def all_packages(self) -> list[PackageInfo]: ...
    def download(self, ref: PackageRef) -> Path:
        """Downloads an exact version as a zip into its own folder and returns the zip path."""
        ...


class ModManager(Protocol):
    """Gale itself."""

    def is_running(self) -> bool: ...
    def select_profile(self, profile: str) -> None: ...
    def install_package(self, ref: PackageRef) -> None: ...
    def install_local(self, path: Path, profile: str | None) -> None: ...
    def launch(self, profile: str | None, vanilla: bool) -> None: ...


class GameRunner(Protocol):
    """Risk of Rain 2 processes."""

    def game_dir(self) -> Path: ...
    def build_id(self) -> str: ...
    def running_pids(self) -> set[int]: ...
    def start_with_profile(self, profile_dir: Path) -> None: ...
    def kill(self, pids: set[int]) -> None: ...


class Decompiler(Protocol):
    def is_managed(self, path: Path) -> bool | None:
        """True for .NET assemblies, False for native binaries, None for other files."""
        ...
    def decompile(self, dll: Path, out_dir: Path) -> str | None:
        """Writes C# sources into out_dir; returns an error message or None."""
        ...


class MalwareScanner(Protocol):
    def scan(self, path: Path) -> str: ...


class KeyValueCache(Protocol):
    def get(self, key: str) -> dict | None: ...
    def put(self, key: str, value: dict) -> None: ...


class Clock(Protocol):
    def now(self) -> float: ...
    def sleep(self, seconds: float) -> None: ...
